     public static string EmitModuleInitializer(ImmutableArray<TypeModel> models)
     {
          var sb = new StringBuilder();
          sb.AppendLine("// <auto-generated/>");
          sb.AppendLine("#nullable enable");
          sb.AppendLine("using System.Runtime.CompilerServices;");
          sb.AppendLine("using FlashXlsx.Abstractions.Internal;");
          sb.AppendLine();
          sb.AppendLine("namespace FlashXlsx.Generated;");
          sb.AppendLine();
          sb.AppendLine("internal static class FlashXlsxModuleInitializer");
          sb.AppendLine("{");
          sb.AppendLine("    [ModuleInitializer]");
          sb.AppendLine("    internal static void Initialize()");
          sb.AppendLine("    {");

          foreach (var m in models)
          {
               string mapClassName = GetMapClassName(m);
               sb.AppendLine($"        XlsxTypeRegistry.Register({mapClassName}.Instance);");
          }

          sb.AppendLine("    }");
          sb.AppendLine("}");
          return sb.ToString();
     }

     public static string EmitTypeMap(TypeModel model)
     {
          var sb = new StringBuilder();
          string mapClassName = GetMapClassName(model);
          string t = model.FullTypeName;
          bool hasContext = model.ContextTypeFullName is not null;
          string ctx = model.ContextTypeFullName ?? "object";

          sb.AppendLine("// <auto-generated/>");
          sb.AppendLine("#nullable enable");
          sb.AppendLine("using System;");
          sb.AppendLine("using System.Collections.Generic;");
          sb.AppendLine("using System.Globalization;");
          sb.AppendLine("using System.Text.RegularExpressions;");
          sb.AppendLine("using FlashXlsx;");
          sb.AppendLine("using FlashXlsx.Abstractions;");
          sb.AppendLine("using FlashXlsx.Abstractions.Internal;");
          sb.AppendLine();
          sb.AppendLine("namespace FlashXlsx.Generated;");
          sb.AppendLine();

          string interfaces = hasContext
              ? $"IXlsxTypeMap<{t}>, IXlsxTypeMap<{t}, {ctx}>"
              : $"IXlsxTypeMap<{t}>";

          sb.AppendLine($"internal sealed class {mapClassName} : {interfaces}");
          sb.AppendLine("{");
          sb.AppendLine($"    public static readonly {mapClassName} Instance = new();");
          sb.AppendLine();

          var conditionTypes = model.Properties
              .SelectMany(p => new[] { p.RequiredIfConditionType, p.IgnoreIfConditionType })
              .Where(c => c is not null)
              .Distinct()
              .ToList();

          for (int i = 0; i < conditionTypes.Count; i++)
          {
               sb.AppendLine($"    private static readonly {conditionTypes[i]} _cond{i} = new();");
          }
          if (conditionTypes.Count > 0) sb.AppendLine();

          for (int i = 0; i < model.Properties.Length; i++)
          {
               var p = model.Properties[i];
               if (p.RegexPattern is not null)
               {
                    string regexOpts = p.RegexIgnoreCase
                        ? "RegexOptions.Compiled | RegexOptions.IgnoreCase | RegexOptions.CultureInvariant"
                        : "RegexOptions.Compiled | RegexOptions.CultureInvariant";
                    sb.AppendLine($"    private static readonly Regex _regex_{p.Name} = new(\"{EscapeString(p.RegexPattern)}\", {regexOpts});");
               }
          }
          if (model.Properties.Any(p => p.RegexPattern is not null)) sb.AppendLine();

          // ColumnCount
          sb.AppendLine($"    public int ColumnCount => {model.Properties.Length};");
          sb.AppendLine();

          // CreateInstance (avec initialisation des [XlsxDefault])
          sb.AppendLine($"    public {t} CreateInstance()");
          sb.AppendLine("    {");
          sb.AppendLine($"        var instance = new {t}();");
          foreach (var p in model.Properties)
          {
               if (p.HasDefaultValue)
               {
                    string literal = FormatDefaultValueLiteral(p);
                    sb.AppendLine($"        instance.{p.Name} = {literal};");
               }
          }
          sb.AppendLine("        return instance;");
          sb.AppendLine("    }");
          sb.AppendLine();

          // GetFixedColumnIndex ([XlsxColumnLetter])
          sb.AppendLine("    public int GetFixedColumnIndex(int propertyIndex) => propertyIndex switch");
          sb.AppendLine("    {");
          for (int i = 0; i < model.Properties.Length; i++)
          {
               if (model.Properties[i].FixedColumnIndex >= 0)
                    sb.AppendLine($"        {i} => {model.Properties[i].FixedColumnIndex},");
          }
          sb.AppendLine("        _ => -1");
          sb.AppendLine("    };");
          sb.AppendLine();

          // GetDropdownValues ([XlsxAllowedValues] ou enum)
          sb.AppendLine("    public string[]? GetDropdownValues(int propertyIndex) => propertyIndex switch");
          sb.AppendLine("    {");
          for (int i = 0; i < model.Properties.Length; i++)
          {
               var p = model.Properties[i];
               if (!p.AllowedValues.IsDefaultOrEmpty)
               {
                    string items = string.Join(", ", p.AllowedValues.Select(v => $"\"{EscapeString(v)}\""));
                    sb.AppendLine($"        {i} => new string[] {{ {items} }},");
               }
               else if (p.Kind == SupportedPropertyKind.Enum && !p.EnumMembers.IsDefaultOrEmpty)
               {
                    var labels = p.EnumMembers.Select(m => p.EnumMode == 2 ? m.Label : m.MemberName);
                    string items = string.Join(", ", labels.Select(v => $"\"{EscapeString(v)}\""));
                    sb.AppendLine($"        {i} => new string[] {{ {items} }},");
               }
          }
          sb.AppendLine("        _ => null");
          sb.AppendLine("    };");
          sb.AppendLine();

          // GetPropertyName
          sb.AppendLine("    public string GetPropertyName(int propertyIndex) => propertyIndex switch");
          sb.AppendLine("    {");
          for (int i = 0; i < model.Properties.Length; i++)
               sb.AppendLine($"        {i} => \"{EscapeString(model.Properties[i].Name)}\",");
          sb.AppendLine("        _ => string.Empty");
          sb.AppendLine("    };");
          sb.AppendLine();

          // GetDefaultHeaderName
          sb.AppendLine("    public string GetDefaultHeaderName(int propertyIndex) => propertyIndex switch");
          sb.AppendLine("    {");
          for (int i = 0; i < model.Properties.Length; i++)
               sb.AppendLine($"        {i} => \"{EscapeString(model.Properties[i].HeaderName)}\",");
          sb.AppendLine("        _ => string.Empty");
          sb.AppendLine("    };");
          sb.AppendLine();

          // ResolvePropertyIndex
          sb.AppendLine("    public int ResolvePropertyIndex(ReadOnlySpan<char> headerOrPropertyName)");
          sb.AppendLine("    {");
          for (int i = 0; i < model.Properties.Length; i++)
          {
               var p = model.Properties[i];
               if (string.Equals(p.Name, p.HeaderName, StringComparison.OrdinalIgnoreCase))
               {
                    sb.AppendLine($"        if (headerOrPropertyName.Equals(\"{EscapeString(p.Name)}\", StringComparison.OrdinalIgnoreCase)) return {i};");
               }
               else
               {
                    sb.AppendLine($"        if (headerOrPropertyName.Equals(\"{EscapeString(p.HeaderName)}\", StringComparison.OrdinalIgnoreCase) || headerOrPropertyName.Equals(\"{EscapeString(p.Name)}\", StringComparison.OrdinalIgnoreCase)) return {i};");
               }
          }
          sb.AppendLine("        return -1;");
          sb.AppendLine("    }");
          sb.AppendLine();

          EmitTrySetCellValue(sb, model);
          EmitValidateRow(sb, model, conditionTypes, withContext: false);
          if (hasContext) EmitValidateRow(sb, model, conditionTypes, withContext: true);

          EmitTryFormatCellValue(sb, model, conditionTypes, withContext: false);
          if (hasContext) EmitTryFormatCellValue(sb, model, conditionTypes, withContext: true);

          sb.AppendLine("}");
          return sb.ToString();
     }

     private static void EmitTrySetCellValue(StringBuilder sb, TypeModel model)
     {
          sb.AppendLine($"    public XlsxCellStatus TrySetCellValue(ref {model.FullTypeName} instance, int propertyIndex, ReadOnlySpan<char> rawValue, bool isNumericCell, XlsxReadOptions options)");
          sb.AppendLine("    {");
          sb.AppendLine("        switch (propertyIndex)");
          sb.AppendLine("        {");

          for (int i = 0; i < model.Properties.Length; i++)
          {
               var p = model.Properties[i];
               sb.AppendLine($"            case {i}: // {p.Name}");
               sb.AppendLine("            {");

               if (p.Kind == SupportedPropertyKind.String)
               {
                    sb.AppendLine("                if (rawValue.IsEmpty) return XlsxCellStatus.Empty;");
                    sb.AppendLine("                if (options.SecurityPolicy == XlsxSecurityPolicy.Reject && XlsxSecuritySanitizer.IsPotentiallyDangerous(rawValue))");
                    sb.AppendLine("                    return XlsxCellStatus.SecurityViolation;");
                    sb.AppendLine();
                    sb.AppendLine("                string strVal = rawValue.ToString();");

                    if (p.TrimMode != 0 || p.TextCase != 0)
                         sb.AppendLine($"                strVal = XlsxSecuritySanitizer.TransformText(strVal, (XlsxTrimMode){p.TrimMode}, (XlsxTextCase){p.TextCase});");

                    if (p.MinLength.HasValue)
                         sb.AppendLine($"                if (strVal.Length < {p.MinLength.Value}) return XlsxCellStatus.LengthInvalid;");
                    if (p.MaxLength.HasValue)
                         sb.AppendLine($"                if (strVal.Length > {p.MaxLength.Value}) return XlsxCellStatus.LengthInvalid;");

                    if (p.RegexPattern is not null)
                         sb.AppendLine($"                if (!_regex_{p.Name}.IsMatch(strVal)) return XlsxCellStatus.PatternMismatch;");

                    if (!p.AllowedValues.IsDefaultOrEmpty)
                    {
                         string comp = p.AllowedValuesIgnoreCase ? "StringComparison.OrdinalIgnoreCase" : "StringComparison.Ordinal";
                         var checks = p.AllowedValues.Select(v => $"!strVal.Equals(\"{EscapeString(v)}\", {comp})");
                         sb.AppendLine($"                if ({string.Join(" && ", checks)}) return XlsxCellStatus.ValueNotAllowed;");
                    }

                    sb.AppendLine($"                instance.{p.Name} = strVal;");
                    sb.AppendLine("                return XlsxCellStatus.Success;");
               }
               else if (p.Kind is SupportedPropertyKind.StringArray or SupportedPropertyKind.StringList)
               {
                    sb.AppendLine("                if (rawValue.IsEmpty) return XlsxCellStatus.Empty;");
                    sb.AppendLine("                if (options.SecurityPolicy == XlsxSecurityPolicy.Reject && XlsxSecuritySanitizer.IsPotentiallyDangerous(rawValue))");
                    sb.AppendLine("                    return XlsxCellStatus.SecurityViolation;");

                    char sep = p.SplitSeparator ?? ';';
                    string trimBool = p.SplitTrimEntries ? "true" : "false";
                    string remEmptyBool = p.SplitRemoveEmptyEntries ? "true" : "false";
                    sb.AppendLine($"                var items = XlsxPrimitiveParser.SplitStringList(rawValue, '{EscapeChar(sep)}', {trimBool}, {remEmptyBool});");

                    if (p.Kind == SupportedPropertyKind.StringArray)
                         sb.AppendLine($"                instance.{p.Name} = items;");
                    else
                         sb.AppendLine($"                instance.{p.Name} = new List<string>(items);");

                    sb.AppendLine("                return XlsxCellStatus.Success;");
               }
               else if (p.Kind == SupportedPropertyKind.Boolean)
               {
                    string trueArr = FormatStringArrayLiteral(p.BoolTrueValues, "options.DefaultTrueValues");
                    string falseArr = FormatStringArrayLiteral(p.BoolFalseValues, "options.DefaultFalseValues");
                    sb.AppendLine($"                var status = XlsxPrimitiveParser.TryParseBoolean(rawValue, {trueArr}, {falseArr}, out bool val);");
                    sb.AppendLine($"                if (status == XlsxCellStatus.Success) instance.{p.Name} = val;");
                    sb.AppendLine("                return status;");
               }
               else if (p.Kind == SupportedPropertyKind.Enum)
               {
                    sb.AppendLine("                if (rawValue.IsEmpty) return XlsxCellStatus.Empty;");

                    if (!p.AllowedValues.IsDefaultOrEmpty)
                    {
                         string comp = p.AllowedValuesIgnoreCase ? "StringComparison.OrdinalIgnoreCase" : "StringComparison.Ordinal";
                         var checks = p.AllowedValues.Select(v => $"!rawValue.Equals(\"{EscapeString(v)}\", {comp})");
                         sb.AppendLine($"                if ({string.Join(" && ", checks)}) return XlsxCellStatus.ValueNotAllowed;");
                    }

                    foreach (var m in p.EnumMembers)
                    {
                         sb.AppendLine($"                if (rawValue.Equals(\"{EscapeString(m.MemberName)}\", StringComparison.OrdinalIgnoreCase) || rawValue.Equals(\"{EscapeString(m.Label)}\", StringComparison.OrdinalIgnoreCase) || rawValue.Equals(\"{m.NumericValue.ToString(CultureInfo.InvariantCulture)}\", StringComparison.Ordinal))");
                         sb.AppendLine($"                {{ instance.{p.Name} = {p.UnderlyingTypeFullName}.{m.MemberName}; return XlsxCellStatus.Success; }}");
                    }
                    sb.AppendLine("                return XlsxCellStatus.InvalidFormat;");
               }
               else
               {
                    string sepExpr = p.DecimalSeparator.HasValue
                        ? $"'{EscapeChar(p.DecimalSeparator.Value)}'"
                        : "options.DecimalSeparator";

                    string parserCall = p.Kind switch
                    {
                         SupportedPropertyKind.Int32 => "XlsxPrimitiveParser.TryParseInt32(rawValue, options.Culture, out int val)",
                         SupportedPropertyKind.Int64 => "XlsxPrimitiveParser.TryParseInt64(rawValue, options.Culture, out long val)",
                         SupportedPropertyKind.Double => $"XlsxPrimitiveParser.TryParseDoubleFlexible(rawValue, isNumericCell, {sepExpr}, options.Culture, out double val)",
                         SupportedPropertyKind.Decimal => $"XlsxPrimitiveParser.TryParseDecimalFlexible(rawValue, isNumericCell, {sepExpr}, options.Culture, out decimal val)",
                         SupportedPropertyKind.DateTime => p.Format is not null
                              ? $"XlsxPrimitiveParser.TryParseDateTimeExact(rawValue, isNumericCell, \"{EscapeString(p.Format)}\", options.Culture, out DateTime val, options.Use1904DateSystem)"
                              : "XlsxPrimitiveParser.TryParseDateTime(rawValue, isNumericCell, options.Culture, out DateTime val, options.Use1904DateSystem)",
                         SupportedPropertyKind.DateOnly => p.Format is not null
                             ? $"XlsxPrimitiveParser.TryParseDateOnlyExact(rawValue, isNumericCell, \"{EscapeString(p.Format)}\", options.Culture, out DateOnly val, options.Use1904DateSystem)"
                             : "XlsxPrimitiveParser.TryParseDateOnly(rawValue, isNumericCell, options.Culture, out DateOnly val, options.Use1904DateSystem)",
                         SupportedPropertyKind.TimeOnly => "XlsxPrimitiveParser.TryParseTimeOnly(rawValue, isNumericCell, options.Culture, out TimeOnly val)",
                         SupportedPropertyKind.Guid => "XlsxPrimitiveParser.TryParseGuid(rawValue, out Guid val)",
                         _ => "XlsxCellStatus.InvalidFormat"
                    };

                    sb.AppendLine($"                var status = {parserCall};");
                    sb.AppendLine("                if (status != XlsxCellStatus.Success) return status;");

                    if (p.Kind is SupportedPropertyKind.Int32 or SupportedPropertyKind.Int64 or SupportedPropertyKind.Double or SupportedPropertyKind.Decimal)
                    {
                         string castVal = p.Kind == SupportedPropertyKind.Decimal ? "(double)val" : "val";
                         if (p.MinValue.HasValue)
                         {
                              string minLiteral = p.MinValue.Value.ToString("R", CultureInfo.InvariantCulture);
                              sb.AppendLine($"                if ({castVal} < {minLiteral}) return XlsxCellStatus.OutOfRange;");
                         }
                         if (p.MaxValue.HasValue)
                         {
                              string maxLiteral = p.MaxValue.Value.ToString("R", CultureInfo.InvariantCulture);
                              sb.AppendLine($"                if ({castVal} > {maxLiteral}) return XlsxCellStatus.OutOfRange;");
                         }
                    }

                    sb.AppendLine($"                instance.{p.Name} = val;");
                    sb.AppendLine("                return XlsxCellStatus.Success;");
               }

               sb.AppendLine("            }");
          }

          sb.AppendLine("            default:");
          sb.AppendLine("                return XlsxCellStatus.ColumnNotFound;");
          sb.AppendLine("        }");
          sb.AppendLine("    }");
          sb.AppendLine();
     }

     private static void EmitValidateRow(StringBuilder sb, TypeModel model, List<string?> conditionTypes, bool withContext)
     {
          string sig = withContext
              ? $"    public bool ValidateRow(ref {model.FullTypeName} instance, in {model.ContextTypeFullName} context, int rowNumber, ReadOnlySpan<int> propertyToExcelColIndex, ReadOnlySpan<string?> excelHeaders, XlsxReadOptions<{model.FullTypeName}, {model.ContextTypeFullName}> options)"
              : $"    public bool ValidateRow(ref {model.FullTypeName} instance, int rowNumber, ReadOnlySpan<int> propertyToExcelColIndex, ReadOnlySpan<string?> excelHeaders, XlsxReadOptions options)";

          sb.AppendLine(sig);
          sb.AppendLine("    {");
          sb.AppendLine("        bool isValid = true;");

          for (int i = 0; i < model.Properties.Length; i++)
          {
               var p = model.Properties[i];

               if (p.IgnoreIfConditionType is not null)
               {
                    if (p.IgnoreIfHasContext && !withContext)
                    {
                         EmitRequiredCheck(sb, p, i, conditionTypes, withContext, "        ");
                    }
                    else
                    {
                         int condIdx = conditionTypes.IndexOf(p.IgnoreIfConditionType);
                         string evalCall = p.IgnoreIfHasContext
                             ? $"_cond{condIdx}.Evaluate(instance, context)"
                             : $"_cond{condIdx}.Evaluate(instance)";

                         sb.AppendLine($"        if ({evalCall})");
                         sb.AppendLine("        {");
                         sb.AppendLine($"            instance.{p.Name} = default!;");
                         sb.AppendLine("        }");
                         sb.AppendLine("        else");
                         sb.AppendLine("        {");
                         EmitRequiredCheck(sb, p, i, conditionTypes, withContext, "            ");
                         sb.AppendLine("        }");
                    }
               }
               else
               {
                    EmitRequiredCheck(sb, p, i, conditionTypes, withContext, "        ");
               }
          }

          sb.AppendLine("        return isValid;");
          sb.AppendLine("    }");
          sb.AppendLine();
     }

     private static void EmitRequiredCheck(StringBuilder sb, PropertyModel p, int propIndex, List<string?> conditionTypes, bool withContext, string indent)
     {
          if (!p.IsRequired && p.RequiredIfConditionType is null)
               return;

          if (!p.IsRequired && p.RequiredIfHasContext && !withContext)
               return;

          string condExpr;
          if (p.IsRequired)
          {
               condExpr = "true";
          }
          else
          {
               int condIdx = conditionTypes.IndexOf(p.RequiredIfConditionType!);
               condExpr = p.RequiredIfHasContext
                   ? (withContext ? $"_cond{condIdx}.Evaluate(instance, context)" : "false")
                   : $"_cond{condIdx}.Evaluate(instance)";
          }

          string emptyCheck = p.Kind switch
          {
               SupportedPropertyKind.String => $"string.IsNullOrWhiteSpace(instance.{p.Name})",
               SupportedPropertyKind.StringArray => $"instance.{p.Name} is null || instance.{p.Name}.Length == 0",
               SupportedPropertyKind.StringList => $"instance.{p.Name} is null || instance.{p.Name}.Count == 0",
               _ => p.IsNullable
                   ? $"instance.{p.Name} is null"
                   : $"EqualityComparer<{p.UnderlyingTypeFullName}>.Default.Equals(instance.{p.Name}, default)"
          };

          sb.AppendLine($"{indent}if ({condExpr} && {emptyCheck})");
          sb.AppendLine($"{indent}{{");
          sb.AppendLine($"{indent}    isValid = false;");
          sb.AppendLine($"{indent}    int excelCol = propertyToExcelColIndex[{propIndex}];");
          sb.AppendLine($"{indent}    string? colHeader = (excelCol >= 0 && excelCol < excelHeaders.Length) ? excelHeaders[excelCol] : \"{EscapeString(p.HeaderName)}\";");
          sb.AppendLine($"{indent}    var err = new XlsxErrorContext(rowNumber, excelCol, string.Empty, colHeader, string.Empty, XlsxCellStatus.RequiredMissing);");
          sb.AppendLine($"{indent}    options.OnError?.Invoke(in err);");
          sb.AppendLine($"{indent}    if (options.ErrorMode == XlsxErrorMode.StopOnFirstError) return false;");
          sb.AppendLine($"{indent}}}");
     }

     private static void EmitTryFormatCellValue(StringBuilder sb, TypeModel model, List<string?> conditionTypes, bool withContext)
     {
          string sig = withContext
              ? $"    public bool TryFormatCellValue(in {model.FullTypeName} instance, in {model.ContextTypeFullName} context, int propertyIndex, int rowNumber, Span<char> destination, out int charsWritten, out string? stringValue, out XlsxCellWriteKind writeKind, XlsxWriteOptions<{model.FullTypeName}, {model.ContextTypeFullName}> options)"
              : $"    public bool TryFormatCellValue(in {model.FullTypeName} instance, int propertyIndex, int rowNumber, Span<char> destination, out int charsWritten, out string? stringValue, out XlsxCellWriteKind writeKind, XlsxWriteOptions options)";

          sb.AppendLine(sig);
          sb.AppendLine("    {");
          sb.AppendLine("        charsWritten = 0;");
          sb.AppendLine("        stringValue = null;");
          sb.AppendLine("        writeKind = XlsxCellWriteKind.Empty;");
          sb.AppendLine("        switch (propertyIndex)");
          sb.AppendLine("        {");

          for (int i = 0; i < model.Properties.Length; i++)
          {
               var p = model.Properties[i];
               sb.AppendLine($"            case {i}:");
               sb.AppendLine("            {");

               if (p.IgnoreIfConditionType is not null && (!p.IgnoreIfHasContext || withContext))
               {
                    int condIdx = conditionTypes.IndexOf(p.IgnoreIfConditionType);
                    string evalCall = p.IgnoreIfHasContext
                        ? $"_cond{condIdx}.Evaluate(instance, context)"
                        : $"_cond{condIdx}.Evaluate(instance)";
                    sb.AppendLine($"                if ({evalCall}) return false;");
               }

               if (p.Formula is not null)
               {
                    string escapedFormula = EscapeString(p.Formula);
                    sb.AppendLine($"                stringValue = \"{escapedFormula}\".Replace(\"{{Row}}\", rowNumber.ToString(CultureInfo.InvariantCulture), StringComparison.OrdinalIgnoreCase);");
                    sb.AppendLine("                writeKind = XlsxCellWriteKind.Formula;");
                    sb.AppendLine("                return true;");
                    sb.AppendLine("            }");
                    continue;
               }

               if (p.HasDefaultValue && p.DefaultApplyOnExport && (p.IsNullable || p.Kind is SupportedPropertyKind.String or SupportedPropertyKind.StringArray or SupportedPropertyKind.StringList))
               {
                    string defLit = FormatDefaultValueLiteral(p);
                    sb.AppendLine($"                var effectiveVal = instance.{p.Name} ?? {defLit};");
               }

               if (p.HasDefaultValue && p.DefaultApplyOnExport && (p.IsNullable || p.Kind == SupportedPropertyKind.String))
               {
                    string defLit = FormatDefaultValueLiteral(p);
                    sb.AppendLine($"                var propVal = instance.{p.Name} ?? ({p.TypeFullName}){defLit};");
               }
               else
               {
                    if (p.IsNullable || p.Kind is SupportedPropertyKind.String or SupportedPropertyKind.StringArray or SupportedPropertyKind.StringList)
                         sb.AppendLine($"                if (instance.{p.Name} is null) return false;");
                    sb.AppendLine($"                var propVal = instance.{p.Name};");
               }
               string access = p.IsNullable ? "propVal.Value" : "propVal";

               switch (p.Kind)
               {
                    case SupportedPropertyKind.String:
                         sb.AppendLine($"                string outStr = propVal;");
                         if (p.TrimMode != 0 || p.TextCase != 0)
                              sb.AppendLine($"                outStr = XlsxSecuritySanitizer.TransformText(outStr, (XlsxTrimMode){p.TrimMode}, (XlsxTextCase){p.TextCase});");
                         sb.AppendLine("                stringValue = options.SecurityPolicy == XlsxSecurityPolicy.Sanitize");
                         sb.AppendLine("                    ? XlsxSecuritySanitizer.SanitizeForExport(outStr, isExplicitFormula: false)");
                         sb.AppendLine("                    : outStr;");
                         sb.AppendLine("                writeKind = XlsxCellWriteKind.InlineString;");
                         sb.AppendLine("                return true;");
                         break;

                    case SupportedPropertyKind.StringArray:
                    case SupportedPropertyKind.StringList:
                         char joinSep = p.SplitSeparator ?? ';';
                         sb.AppendLine($"                string joined = string.Join('{EscapeChar(joinSep)}', propVal);");
                         sb.AppendLine("                stringValue = options.SecurityPolicy == XlsxSecurityPolicy.Sanitize");
                         sb.AppendLine("                    ? XlsxSecuritySanitizer.SanitizeForExport(joined, isExplicitFormula: false)");
                         sb.AppendLine("                    : joined;");
                         sb.AppendLine("                writeKind = XlsxCellWriteKind.InlineString;");
                         sb.AppendLine("                return true;");
                         break;

                    case SupportedPropertyKind.Int32:
                    case SupportedPropertyKind.Int64:
                    case SupportedPropertyKind.Double:
                    case SupportedPropertyKind.Decimal:
                         if (p.Format is not null || p.DecimalSeparator.HasValue)
                         {
                              string fmtArg = p.Format is not null ? $"\"{EscapeString(p.Format)}\"" : "null";
                              sb.AppendLine($"                string formattedNum = {access}.ToString({fmtArg}, CultureInfo.InvariantCulture);");
                              if (p.DecimalSeparator.HasValue)
                              {
                                   if (p.DecimalSeparator.Value != '.')
                                   {
                                        sb.AppendLine($"                formattedNum = formattedNum.Replace('.', '{EscapeChar(p.DecimalSeparator.Value)}');");
                                   }
                              }
                              else
                              {
                                   sb.AppendLine("                if (options.DecimalSeparator != '.') formattedNum = formattedNum.Replace('.', options.DecimalSeparator);");
                              }
                              sb.AppendLine("                stringValue = formattedNum;");
                              sb.AppendLine("                writeKind = XlsxCellWriteKind.InlineString;");
                              sb.AppendLine("                return true;");
                         }
                         else
                         {
                              sb.AppendLine($"                if ({access}.TryFormat(destination, out charsWritten, provider: CultureInfo.InvariantCulture))");
                              sb.AppendLine("                {");
                              sb.AppendLine("                    writeKind = XlsxCellWriteKind.Number;");
                              sb.AppendLine("                    return true;");
                              sb.AppendLine("                }");
                              sb.AppendLine("                return false;");
                         }
                         break;

                    case SupportedPropertyKind.DateTime:
                         if (p.Format is not null)
                         {
                              sb.AppendLine($"                stringValue = {access}.ToString(\"{EscapeString(p.Format)}\", options.Culture);");
                              sb.AppendLine("                writeKind = XlsxCellWriteKind.InlineString;");
                              sb.AppendLine("                return true;");
                         }
                         else
                         {
                              sb.AppendLine($"                if ({access}.ToOADate().TryFormat(destination, out charsWritten, provider: CultureInfo.InvariantCulture))");
                              sb.AppendLine("                {");
                              sb.AppendLine("                    writeKind = XlsxCellWriteKind.DateTime;");
                              sb.AppendLine("                    return true;");
                              sb.AppendLine("                }");
                              sb.AppendLine("                return false;");
                         }
                         break;

                    case SupportedPropertyKind.DateOnly:
                         if (p.Format is not null)
                         {
                              sb.AppendLine($"                stringValue = {access}.ToString(\"{EscapeString(p.Format)}\", options.Culture);");
                              sb.AppendLine("                writeKind = XlsxCellWriteKind.InlineString;");
                              sb.AppendLine("                return true;");
                         }
                         else
                         {
                              sb.AppendLine($"                if ({access}.ToDateTime(TimeOnly.MinValue).ToOADate().TryFormat(destination, out charsWritten, provider: CultureInfo.InvariantCulture))");
                              sb.AppendLine("                {");
                              sb.AppendLine("                    writeKind = XlsxCellWriteKind.Date;");
                              sb.AppendLine("                    return true;");
                              sb.AppendLine("                }");
                              sb.AppendLine("                return false;");
                         }
                         break;

                    case SupportedPropertyKind.TimeOnly:
                         sb.AppendLine($"                if ({access}.ToTimeSpan().TotalDays.TryFormat(destination, out charsWritten, provider: CultureInfo.InvariantCulture))");
                         sb.AppendLine("                {");
                         sb.AppendLine("                    writeKind = XlsxCellWriteKind.Time;");
                         sb.AppendLine("                    return true;");
                         sb.AppendLine("                }");
                         sb.AppendLine("                return false;");
                         break;

                    case SupportedPropertyKind.Guid:
                         sb.AppendLine($"                if ({access}.TryFormat(destination, out charsWritten))");
                         sb.AppendLine("                {");
                         sb.AppendLine("                    writeKind = XlsxCellWriteKind.InlineString;");
                         sb.AppendLine("                    return true;");
                         sb.AppendLine("                }");
                         sb.AppendLine("                return false;");
                         break;

                    case SupportedPropertyKind.Boolean:
                         if (p.BoolTrueValues.Length > 0 || p.BoolFalseValues.Length > 0)
                         {
                              string trueStr = p.BoolTrueValues.Length > 0 ? $"\"{EscapeString(p.BoolTrueValues[0])}\"" : "\"\"";
                              string falseStr = p.BoolFalseValues.Length > 0 ? $"\"{EscapeString(p.BoolFalseValues[0])}\"" : "\"\"";
                              sb.AppendLine($"                stringValue = {access} ? {trueStr} : {falseStr};");
                              sb.AppendLine("                writeKind = XlsxCellWriteKind.InlineString;");
                              sb.AppendLine("                return true;");
                         }
                         else
                         {
                              sb.AppendLine("                if (options.DefaultTrueValues is { Length: > 0 } || options.DefaultFalseValues is { Length: > 0 })");
                              sb.AppendLine("                {");
                              sb.AppendLine($"                    stringValue = {access}");
                              sb.AppendLine("                        ? (options.DefaultTrueValues is { Length: > 0 } ? options.DefaultTrueValues[0] : string.Empty)");
                              sb.AppendLine("                        : (options.DefaultFalseValues is { Length: > 0 } ? options.DefaultFalseValues[0] : string.Empty);");
                              sb.AppendLine("                    writeKind = XlsxCellWriteKind.InlineString;");
                              sb.AppendLine("                    return true;");
                              sb.AppendLine("                }");
                              sb.AppendLine($"                destination[0] = {access} ? '1' : '0';");
                              sb.AppendLine("                charsWritten = 1;");
                              sb.AppendLine("                writeKind = XlsxCellWriteKind.Boolean;");
                              sb.AppendLine("                return true;");
                         }
                         break;

                    case SupportedPropertyKind.Enum:
                         if (p.EnumMode == 1)
                         {
                              sb.AppendLine($"                if (((long){access}).TryFormat(destination, out charsWritten, provider: CultureInfo.InvariantCulture))");
                              sb.AppendLine("                {");
                              sb.AppendLine("                    writeKind = XlsxCellWriteKind.Number;");
                              sb.AppendLine("                    return true;");
                              sb.AppendLine("                }");
                              sb.AppendLine("                return false;");
                         }
                         else
                         {
                              sb.AppendLine($"                stringValue = {access} switch");
                              sb.AppendLine("                {");
                              foreach (var m in p.EnumMembers)
                              {
                                   string outText = p.EnumMode == 2 ? m.Label : m.MemberName;
                                   sb.AppendLine($"                    {p.UnderlyingTypeFullName}.{m.MemberName} => \"{EscapeString(outText)}\",");
                              }
                              sb.AppendLine($"                    _ => {access}.ToString()");
                              sb.AppendLine("                };");
                              sb.AppendLine("                writeKind = XlsxCellWriteKind.InlineString;");
                              sb.AppendLine("                return true;");
                         }
                         break;

                    default:
                         sb.AppendLine("                return false;");
                         break;
               }

               sb.AppendLine("            }");
          }

          sb.AppendLine("            default:");
          sb.AppendLine("                return false;");
          sb.AppendLine("        }");
          sb.AppendLine("    }");
     }

     private static string FormatDefaultValueLiteral(PropertyModel p)
     {
          if (p.DefaultKind != 0)
          {
               return p.DefaultKind switch
               {
                    1 => p.Kind == SupportedPropertyKind.DateOnly ? "DateOnly.FromDateTime(DateTime.Now)" : "DateTime.Now",
                    2 => p.Kind == SupportedPropertyKind.DateOnly ? "DateOnly.FromDateTime(DateTime.UtcNow)" : "DateTime.UtcNow",
                    3 => p.Kind == SupportedPropertyKind.DateOnly ? "DateOnly.FromDateTime(DateTime.Today)" : "DateTime.Today",
                    4 => "Guid.NewGuid()",
                    5 => "string.Empty",
                    _ => "default!"
               };
          }

          if (p.DefaultValue is null)
               return "default!";

          if (p.Kind == SupportedPropertyKind.Enum)
          {
               if (p.DefaultValue is string enumStr)
                    return $"{p.UnderlyingTypeFullName}.{enumStr}";
               return $"({p.UnderlyingTypeFullName}){Convert.ToInt64(p.DefaultValue)}";
          }

          return p.DefaultValue switch
          {
               string s => $"\"{EscapeString(s)}\"",
               bool b => b ? "true" : "false",
               int i => i.ToString(CultureInfo.InvariantCulture),
               long l => $"{l.ToString(CultureInfo.InvariantCulture)}L",
               double d when p.Kind == SupportedPropertyKind.Decimal => $"{d.ToString("R", CultureInfo.InvariantCulture)}m",
               double d => $"{d.ToString("R", CultureInfo.InvariantCulture)}d",
               float f when p.Kind == SupportedPropertyKind.Decimal => $"{f.ToString("R", CultureInfo.InvariantCulture)}m",
               float f => $"{f.ToString("R", CultureInfo.InvariantCulture)}f",
               _ => $"({p.TypeFullName})\"{EscapeString(p.DefaultValue.ToString() ?? string.Empty)}\""
          };
     }

     private static string GetMapClassName(TypeModel m)
         => $"{m.FullTypeName.Replace("global::", "").Replace(".", "_").Replace("<", "_").Replace(">", "_")}_XlsxMap";

     private static string FormatStringArrayLiteral(ImmutableArray<string> arr, string fallbackExpr)
     {
          if (arr.IsDefaultOrEmpty)
               return fallbackExpr;

          return $"new string[] {{ {string.Join(", ", arr.Select(s => $"\"{EscapeString(s)}\""))} }}";
     }

     private static string EscapeString(string s)
         => s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n");

     private static string EscapeChar(char c)
         => c switch
         {
              '\\' => "\\\\",
              '\'' => "\\'",
              '\0' => "\\0",
              '\t' => "\\t",
              '\r' => "\\r",
              '\n' => "\\n",
              _ => c.ToString()
         };
